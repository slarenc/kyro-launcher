const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
process.env.TZ='Asia/Novosibirsk';
const source=fs.readFileSync(path.join(__dirname,'../ui/app.js'),'utf8');
const context=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function dateKey('),source.indexOf('const s=()=>')),context);
const streak=(sessions,now)=>context.activityStreak(sessions,new Date(now));
const session=(started,seconds=60)=>({started,seconds});
const history=Array.from({length:12},(_,i)=>session(`2026-11-${String(i+7).padStart(2,'0')}T12:00:00+07:00`));
assert.equal(streak(history,'2026-11-18T18:00:00+07:00'),12,'continuous saved history');
assert.equal(streak(history,'2026-11-19T09:00:00+07:00'),12,'today is still available to continue');
assert.equal(streak(history,'2026-11-20T09:00:00+07:00'),0,'a full missed day resets the streak');
assert.equal(streak([...history,history[0]],'2026-11-18T18:00:00+07:00'),12,'multiple sessions do not add days');
assert.equal(streak(history.filter((_,i)=>i!==10),'2026-11-18T18:00:00+07:00'),1,'a real gap breaks the streak');
assert.equal(streak([session('2026-11-16T23:30:00+07:00',26*3600)],'2026-11-18T18:00:00+07:00'),3,'play across midnight continues the streak');
assert.equal(streak([session('2026-11-17T23:30:00+07:00',1800)],'2026-11-18T18:00:00+07:00'),1,'ending at midnight does not add an unplayed day');
assert.equal(streak([session('2026-11-17T17:30:00Z')],'2026-11-19T18:00:00+07:00'),1,'UTC timestamps use the local calendar day');
assert.equal(streak([session('bad date'),session('2026-11-20T12:00:00+07:00')],'2026-11-18T18:00:00+07:00'),0,'invalid and future sessions are ignored');
assert.equal(streak([],'2026-11-18T18:00:00+07:00'),0);
assert.equal(streak([session('2026-12-31T23:30:00+07:00',3600)],'2027-01-01T09:00:00+07:00'),2,'year boundary');
assert.equal(streak([session('2028-02-28T23:30:00+07:00',26*3600)],'2028-03-01T09:00:00+07:00'),3,'leap day');
process.env.TZ='America/New_York';
assert.equal(streak([session('2026-03-07T23:30:00-05:00',24*3600)],'2026-03-09T09:00:00-04:00'),3,'spring daylight saving transition');
assert.equal(streak([session('2026-10-31T23:30:00-04:00',26*3600)],'2026-11-02T09:00:00-05:00'),3,'autumn daylight saving transition');
console.log('PASS: activity streak, local dates, midnight sessions, gaps, duplicates and continuous history.');
