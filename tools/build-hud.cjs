const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {root,msvcEnvironment}=require('./build.cjs');
const env=msvcEnvironment();
const wrapperRoot=path.join(process.env.USERPROFILE,'.gradle/wrapper/dists/gradle-9.2.1-bin');
const localGradle=fs.existsSync(wrapperRoot)?fs.readdirSync(wrapperRoot).map(folder=>path.join(wrapperRoot,folder,'gradle-9.2.1/bin/gradle.bat')).find(file=>fs.existsSync(file)):null;
const gradle=process.env.KYRO_GRADLE || localGradle || 'gradle';
execFileSync(gradle,['-p','components/hud','build','--console=plain'],{cwd:root,env,stdio:'inherit',windowsHide:true,shell:process.platform==='win32'});
const cargo=path.join(process.env.USERPROFILE,'.cargo/bin/cargo.exe');
execFileSync(cargo,['build','--release','--locked','--manifest-path','components/media/Cargo.toml'],{cwd:root,env,stdio:'inherit',windowsHide:true});
for(const name of ['kyro-hud-agent.jar','kyro-hud-runtime.jar'])fs.copyFileSync(path.join(root,'components/hud/build/libs',name),path.join(root,'src-tauri/resources',name));
fs.copyFileSync(path.join(root,'components/media/target/release/kyro-media.exe'),path.join(root,'src-tauri/resources/kyro-media.exe'));
